/// Состояние карты на столе (макет карты, «Состояния карты»). Рисуется на контейнере поверх любого варианта.
enum CardHighlight {
  /// Обычная: тень.
  normal,

  /// Выбрана: подъём, золотое кольцо и свечение.
  selected,

  /// Нельзя сыграть сейчас: обесцвечена и затемнена.
  disabled,

  /// Только что сыграна: светлое кольцо и свечение, затем гаснет.
  justPlayed,

  /// Мой шпион на поле соперника: лента с глазом и пунктир цвета владельца.
  spy,
}
