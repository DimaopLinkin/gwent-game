import 'package:gwent/src/features/lobby/data/online/room_message.dart';

/// Приватный канал комнаты: сообщения хоста и гостя друг другу (ADR 0025). Реализация — Supabase Realtime Broadcast.
///
/// Канал не гарантирует доставку: сообщения, отправленные без связи, теряются. Доставку и порядок обеспечивает
/// протокол партии (нумерация, подтверждения, переотправка, ADR 0005).
abstract interface class RoomChannel {
  /// Сообщения собеседника. Свои сообщения канал не возвращает. Поток общий (broadcast) и не закрывается сам.
  Stream<RoomMessage> get messages;

  /// Каждый раз, когда канал сообщил о неполадке после входа: сокет оборвался, сервер отказал в доступе.
  /// Канал при этом сам пытается вернуться; слушатель выясняет, жива ли ещё комната.
  Stream<void> get trouble;

  /// Отправляет сообщение; без связи оно теряется.
  void send(RoomMessage message);

  /// Покидает канал. Сообщения, отправленные до вызова, уходят раньше. Повторный вызов ничего не делает.
  Future<void> close();
}
