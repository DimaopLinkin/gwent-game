/// Почему лобби не смогло объявить, найти партию или подключиться к ней.
enum LobbyFailure {
  /// Поиск или объявление в сети не работает: нет Wi-Fi, служба ОС отказала. В игре через интернет: нет связи
  /// с сервисом комнат, он не отвечает (бесплатный проект мог уснуть) или не пустил анонимный вход.
  unavailable,

  /// К хосту не удалось подключиться ни по одному адресу: хост ушёл, сеть изолирует клиентов
  /// или партии с таким идентификатором на этом адресе больше нет.
  unreachable,

  /// Игра через интернет: комнаты с таким кодом нет (код неверный, комнату закрыли или срок её жизни вышел).
  codeNotFound,

  /// Игра через интернет: в комнате уже есть другой гость. Хост создаст комнату заново, у неё будет новый код.
  roomFull,

  /// Игра через интернет: хост не принимает гостей.
  roomClosed,

  /// Игра через интернет: игрок ввёл код своей комнаты.
  ownRoom,

  /// Игра через интернет: слишком много неверных кодов подряд, новые попытки не принимаются около десяти минут.
  tooManyAttempts,

  /// Игра через интернет: слишком много созданных комнат за последний час.
  tooManyRooms,
}

/// Ошибка лобби: ловится по типу и показывается игроку по [failure].
final class LobbyException implements Exception {
  /// Создаёт ошибку.
  const LobbyException(this.failure, [this.cause]);

  /// Что не получилось.
  final LobbyFailure failure;

  /// Исходная ошибка платформы, для журнала.
  final Object? cause;

  @override
  String toString() => 'LobbyException(${failure.name}${cause == null ? '' : ', $cause'})';
}
