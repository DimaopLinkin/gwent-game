/// Хранилище сессии анонимного игрока для игры через интернет (ADR 0025, 0026).
///
/// Сессия нужна, чтобы не заводить нового игрока при каждом заходе: вход ограничен по IP. Строка непрозрачна для
/// приложения: её содержимое понимает клиент сервера. Потеря сессии ничего не стоит, игрок войдёт заново.
abstract interface class OnlineSessionStore {
  /// Сохранённая сессия; `null`, если её нет.
  Future<String?> read();

  /// Сохраняет [session] вместо прежней.
  Future<void> write(String session);

  /// Забывает сессию.
  Future<void> clear();
}
