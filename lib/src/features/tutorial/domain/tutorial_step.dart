/// Шаг обучения «Первой партии»: то, что игрок видит на карточке подсказки (ADR 0034).
///
/// Ходы без карточки (свободные ходы игрока и ходы бота) шагами не считаются.
enum TutorialStep {
  /// Цель партии.
  goal(1),

  /// Рука, колода и сброс.
  handAndDeck(2),

  /// Сила и ряд карты.
  cardPower(3),

  /// Первая карта: выбрать и положить в ряд.
  firstCard(4),

  /// Счёт ряда и общий счёт.
  score(5),

  /// Ход соперника.
  opponentMove(6),

  /// Ряды: дальний бой.
  rows(7),

  /// Герой.
  hero(8),

  /// Зачем пасовать.
  passIntro(9),

  /// Пас удержанием.
  passHold(10),

  /// Итог раунда.
  roundResult(11),

  /// Погода.
  weather(12),

  /// Шпион.
  spy(13),

  /// Командирский рог.
  horn(13),

  /// Лидер.
  leader(14),

  /// Пас, которым партия заканчивается.
  finalPass(15)
  ;

  const TutorialStep(this.number);

  /// Сколько шагов в счётчике «Шаг N из 15»: шпион и рог идут под одним номером.
  static const int total = 15;

  /// Номер шага в счётчике.
  final int number;
}
