/// Очередь сценариев, которые выбирают активную колоду или создают стартовые колоды.
///
/// Сценарии сначала смотрят, есть ли у фракции колоды, и только потом создают стартовую. Если два таких сценария
/// идут одновременно (первый запуск и быстрый старт партии), оба увидят пустую фракцию и создадут по колоде.
/// Очередь выполняет их по одному. Один экземпляр на приложение, его разделяют сценарии из точки сборки.
final class DeckSelectionLock {
  Future<void> _tail = Future.value();

  /// Выполняет [action] после всех ранее поставленных действий и возвращает его результат или ошибку.
  Future<T> run<T>(Future<T> Function() action) {
    final result = _tail.then((_) => action());
    // Ошибка действия достаётся вызывающему через result; очередь от неё не останавливается.
    _tail = result.then<void>((_) {}, onError: (Object _) {});
    return result;
  }
}
