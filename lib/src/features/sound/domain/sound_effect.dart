/// Звуковой эффект игры: событие, которое слышит игрок (ADR 0023).
///
/// Названия говорят о событии, а не о файле: какой файл играет, решает реализация в слое data.
enum SoundEffect {
  /// Открылось знакомство с соперником перед партией.
  matchOpening,

  /// Руки розданы, началась пересдача.
  matchStart,

  /// Игрок поменял карту при пересдаче.
  redraw,

  /// Начался первый раунд партии.
  firstRoundStart,

  /// Ход перешёл к игроку.
  turnMine,

  /// Ход перешёл к сопернику.
  turnOpponent,

  /// Кто-то спасовал.
  pass,

  /// Раунд выигран.
  roundWon,

  /// Раунд проигран или сыгран вничью.
  roundLost,

  /// Матч выигран.
  matchWon,

  /// Матч проигран или сыгран вничью.
  matchLost,

  /// Карта пришла из колоды в руку.
  draw,

  /// Отряд ближнего боя встал в ряд.
  unitMelee,

  /// Отряд дальнего боя встал в ряд.
  unitRanged,

  /// Осадный отряд встал в ряд.
  unitSiege,

  /// Герой встал в ряд.
  hero,

  /// Шпион.
  spy,

  /// Медик.
  medic,

  /// Двойник (сбор отряда).
  muster,

  /// Боевой дух.
  morale,

  /// Крепкая связь.
  bond,

  /// Командирский рог.
  horn,

  /// Мардрём.
  mardroeme,

  /// Казнь.
  scorch,

  /// Чучело.
  decoy,

  /// Ясная погода.
  clearWeather,

  /// Пронизывающий мороз.
  frost,

  /// Непроглядный туман.
  fog,

  /// Проливной дождь (и шторм Скеллиге).
  rain,

  /// Игрок выбрал карту.
  select,

  /// Открылся лист (сброс, лидер).
  sheetOpen,

  /// Карта добавлена в колоду в конструкторе.
  deckAdd,

  /// Карта убрана из колоды в конструкторе.
  deckRemove,

  /// Ход или действие отклонены.
  warning,

  /// Открылось главное меню.
  menuOpen,
}
