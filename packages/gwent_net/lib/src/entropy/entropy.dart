/// Источник случайности хоста: сид партии, идентификатор партии и токены переподключения.
///
/// Отдельно от `Rng` движка: сид и токены должны быть непредсказуемы для гостя, а ходы партии
/// воспроизводимы по сиду.
abstract interface class Entropy {
  /// Сид генератора партии.
  int seed();

  /// Непредсказуемая строка: идентификатор партии или токен переподключения.
  String token();
}
