import 'dart:typed_data';

/// Соединение с собеседником: труба для кадров (раздел 6 сетевой спецификации).
///
/// Транспорт ничего не знает о протоколе: кадры кодирует и разбирает `EnvelopeCodec`. Соединение одноразовое:
/// после обрыва клиент получает новый транспорт (тот же вид или другой, например Wi-Fi вместо BLE)
/// и переподключается по токену.
abstract interface class Transport {
  /// Кадры собеседника по порядку. Поток закрывается, когда связь потеряна или закрыта любой стороной.
  Stream<Uint8List> get incoming;

  /// Отправляет кадр. После обрыва кадры молча теряются: о потере говорит закрытие [incoming].
  void send(Uint8List frame);

  /// Закрывает соединение с обеих сторон.
  Future<void> close();
}
