/// Уровень сложности бота-соперника.
///
/// Порядок значений — порядок силы: каждый следующий уровень сильнее предыдущего. Имя значения хранится в настройках
/// игрока, поэтому переименование требует переноса сохранённого значения.
enum BotDifficulty {
  /// Лёгкий: бот иногда ходит наугад, тратит сильные карты первыми, не меняет карты при пересдаче и рано пасует.
  easy,

  /// Нормальный: жадный бот из ADR 0004.
  normal,

  /// Тяжёлый: тратит слабые карты раньше сильных, если лучший ход выигрывает у них не больше шести очков.
  hard,

  /// «НА СМЕРТЬ!»: всегда играет самую дешёвую карту из тех, что не теряют очков, и держит сильные до нужного момента;
  /// колоду собирает из лучших карт.
  deathMatch,
}
