import 'package:gwent_engine/gwent_engine.dart';

/// Соперник-компьютер: выбирает намерение за своего игрока.
///
/// Бот получает полное состояние партии: в одиночной игре оно живёт на том же устройстве, а проверить ход можно
/// только движком. Реализация решает по тому, что видит её игрок (`MatchEngine.project`), и возвращает только
/// намерения, которые движок примет.
abstract interface class MatchBot {
  /// Намерение игрока [seat] или `null`, если сейчас от него ничего не ждут.
  Intent? decide(MatchState state, Seat seat);
}
