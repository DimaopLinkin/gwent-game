/// UUID определения карты отряда или специальной карты из пакета контента. Никогда не меняется.
extension type const CardId(String value) {}

/// UUID карты лидера из пакета контента.
extension type const LeaderId(String value) {}

/// Номер конкретного экземпляра карты в партии.
///
/// Колода может содержать несколько копий одного [CardId]; экземпляры различает этот номер.
/// Номера выдаются в порядке перемешанной колоды, поэтому по номеру нельзя узнать карту соперника.
extension type const CardInstanceId(int value) {}
