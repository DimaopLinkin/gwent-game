/// Как карта отряда вышла на поле. От этого зависит, сработают ли способности при выходе (раздел 9.2).
enum EntrySource {
  /// Разыграна из руки: срабатывают все способности при выходе.
  hand,

  /// Вызвана Медиком: срабатывают все способности при выходе.
  medic,

  /// Призвана Двойником из колоды: срабатывают способности при выходе, кроме самого Двойника.
  musterFromDeck,

  /// Призвана Двойником из руки: срабатывают способности при выходе, кроме самого Двойника.
  musterFromHand,

  /// Вернулась перком Скеллиге: способности при выходе не срабатывают.
  perk
  ;

  /// Карту призвал Двойник. Зона в значении нужна сопернику: он видит только число карт руки и колоды.
  bool get isMuster => this == musterFromDeck || this == musterFromHand;
}
