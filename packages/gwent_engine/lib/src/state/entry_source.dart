/// Как карта отряда вышла на поле. От этого зависит, сработают ли способности при выходе (раздел 9.2).
enum EntrySource {
  /// Разыграна из руки: срабатывают все способности при выходе.
  hand,

  /// Вызвана Медиком: срабатывают все способности при выходе.
  medic,

  /// Призвана Двойником: срабатывают способности при выходе, кроме самого Двойника.
  muster,

  /// Вернулась перком Скеллиге: способности при выходе не срабатывают.
  perk,
}
